const semAcento = (valor) => String(valor || "").normalize("NFD").replace(/[̀-ͯ]/g, "").toLocaleLowerCase("pt-BR");
// "Micro-ondas", "AR-CONDICIONADO", "Geladeiras!" -> "micro ondas", "ar condicionado", "geladeiras".
const normalizar = (valor) => semAcento(valor).replace(/[^a-z0-9]+/g, " ").trim();

// Plural do português só pelo fim da palavra: "televisões" -> "televisao", "fogões" -> "fogao", "papéis" -> "papel".
// Palavras curtas (até 3 letras: "gas", "tv") e terminadas em "ss" ficam; "lapis" vira "lapi", mas a forma digitada é testada antes.
function singular(palavra) {
  if (palavra.length <= 3) return palavra;
  if (/oes$|aes$/.test(palavra)) return `${palavra.slice(0, -3)}ao`;
  if (/ais$/.test(palavra)) return `${palavra.slice(0, -2)}l`;
  if (/eis$/.test(palavra) && palavra.length > 4) return `${palavra.slice(0, -2)}l`;
  if (/(r|z)es$/.test(palavra)) return palavra.slice(0, -2);
  if (/[^s]s$/.test(palavra)) return palavra.slice(0, -1);
  return palavra;
}

// Nomes do catálogo já escritos do jeito do catálogo ("refrigerador duplex", o botão de uma sugestão): vão como estão.
const NOMES_DO_CATALOGO = new Set(Object.values(SINONIMOS).flat().map(normalizar));
// Mais palavras primeiro: "ar condicionado split" antes de "ar condicionado"; "cadeira giratoria" antes de "cadeira".
const CHAVES = Object.keys(SINONIMOS).sort((a, b) => b.split(" ").length - a.split(" ").length || b.length - a.length);

// Produto da tela (sem a especificação: medida, cor, formato) -> tradução ou null.
//   automatico: true  -> o produto inteiro é um termo popular ("geladeira", "televisões"): a busca usa termo (o nome do catálogo);
//   automatico: false -> o produto começa por um termo popular ("geladeira consul", "agua de coco"): busca o que a pessoa
//                        digitou e só oferece as sugestões (trocar sozinho "agua de coco" por água mineral seria errado).
// sugestoes: nomes do catálogo, o 1º é o da busca automática. Plural e acento não importam.
function traduzirTermo(produto) {
  const original = normalizar(produto).split(" ").filter(Boolean);
  if (!original.length || NOMES_DO_CATALOGO.has(original.join(" "))) return null;
  const formas = [original, original.map(singular)];
  const exata = formas.map((f) => f.join(" ")).find((f) => SINONIMOS[f]);
  const chave = exata || CHAVES.find((c) => formas.some((f) => `${f.join(" ")} `.startsWith(`${c} `)));
  if (!chave) return null;
  const [busca, ...outras] = SINONIMOS[chave];
  // "liquidificador" -> "liquidificador": o dicionário só confirma; não há o que trocar nem sugerir.
  if (normalizar(busca) === original.join(" ") && !outras.length) return null;
  return { automatico: Boolean(exata), termo: busca, popular: chave, sugestoes: [busca, ...outras] };
}

// Termos para o robô da pré-consulta: o que as pessoas digitam (a chave da pré-consulta é o termo digitado).
const termosDoDicionario = () => Object.keys(SINONIMOS);

module.exports = { SINONIMOS, traduzirTermo, singular, normalizar, termosDoDicionario };
